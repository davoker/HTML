// Creamos una clase llamada variables
public class variables {
    // Método principal, aquí comienza la ejecución del programa
    public static void main(String[] args) {
        // Variable de tipo int para guardar un número entero
        int edad = 45;
        // Variable de tipo double para guardar un número decimal
        double altura = 1.71;
        // Variable de tipo string para guardar texto
        String nombre = "David";
        // Variable de tipo boolean para guardar true o false
        boolean bailarin = false;

        // Mostramos el contenido de la variable nombre
        System.out.println(nombre);
        // Mostramos el contenido de la variable edad
        System.out.println(edad);
        // Mostramos el contenido de la variable altura
        System.out.println(altura);
        // Mostramos el contenido de la variable bailarin
        System.out.println(bailarin);
    }
}