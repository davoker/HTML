public class variables { // Declara la clase; su nombre coincide con el archivo.
    public static void main(String[] args) {
        int edad = 45; // int guarda un número entero.
        double altura = 1.71; // double guarda un número decimal.
        String nombre = "David"; // String guarda texto entre comillas.
        boolean bailarin = false; // boolean guarda true (verdadero) o false (falso).

        System.out.println(nombre); // Muestra el contenido de nombre.
        System.out.println(edad); // Muestra el contenido de edad.
        System.out.println(altura); // Muestra el contenido de altura.
        System.out.println(bailarin); // Muestra el contenido de bailarin.
    }
}